"""The assistant row records what actually happened, not the column defaults.

`messages.generator` and `messages.search_mode` are `NOT NULL DEFAULT`
(migration 0005), and that choice was deliberate: existing rows were to "get an
honest value rather than `NULL`, which would later be read as 'unknown' and
propagate into evals". For a writer that *knows* the answer, the default is not
honest — it is a confident wrong answer, and worse than `NULL` for exactly the
reason 0005 gives. `store_answer` in `app/api/v1/conversations.py` omitted both
columns, so an answer generated by `gemini-3.6-flash` in `hybrid` mode was
stored as `deterministic` / `fts`.

Nothing reads those columns on the assistant row today, which is why nothing
caught it, and is also why this test matters more than the one-line fix: the
field will stay unread until something depends on it being true, and by then
the wrong rows are already written.

The model is stubbed rather than loaded. `mode="hybrid"` reaches
`_search_vector`, which encodes the *question* through the embedder — the
transitive model dependency `test_search_mode_carrier.py` documents at length —
and the property under test is a property of the writer, not of the weights.
The same applies to the provider: `build_provider` is replaced so a Gemini
choice does not need a key or a network, because what is being proved is that
the *stored* choice reaches the row, not that Gemini answers.
"""

import pytest
from sqlalchemy import text

import app.chat.embedding as embedding_module
from app.api.v1 import conversations
from app.chat.embedding import DIMENSIONS
from app.chat.providers import DEFAULT_GENERATOR, FakeProvider, GeneratorChoice
from app.chat.retrieval import SearchMode
from app.db.session import system_session, tenant_session

# Both deliberately not the column default: `fts` and `deterministic` are what a
# row gets when the writer says nothing, so a test run in the default mode with
# the default generator passes against the bug.
NON_DEFAULT_MODE = SearchMode.HYBRID
NON_DEFAULT_GENERATOR = GeneratorChoice.FLASH


def test_the_chosen_values_are_not_the_column_defaults() -> None:
    """Guards the premise of the test below rather than the code.

    If `DEFAULT_GENERATOR` ever became `FLASH`, or the mode default became
    `hybrid`, the round trip below would still pass — against a `store_answer`
    that wrote nothing at all. This fails first and names why.
    """
    assert NON_DEFAULT_GENERATOR is not DEFAULT_GENERATOR
    assert NON_DEFAULT_MODE is not SearchMode.FTS


class _StubRow(list):
    def tolist(self):
        return list(self)


class _StubModel:
    def embed(self, texts):
        return [_StubRow([0.1] * DIMENSIONS) for _ in texts]


async def _answer_one_question(client, headers, monkeypatch) -> str:
    """POST a question in the non-default mode with the non-default generator,
    stream it to completion, and return the conversation id.

    Streamed to completion on purpose: `store_answer` never runs on the
    cancellation path (`app.chat.stream.generate_events`), so a test that read
    one frame and disconnected would find no assistant row at all and would pass
    an emptiness check while proving nothing.
    """
    monkeypatch.setattr(embedding_module, "_model", _StubModel())
    monkeypatch.setattr(conversations, "build_provider", lambda choice: FakeProvider())

    conversation_id = (
        await client.post("/api/v1/conversations", json={"title": "Demo"}, headers=headers)
    ).json()["id"]
    message_id = (
        await client.post(
            f"/api/v1/conversations/{conversation_id}/messages",
            json={
                "content": "What are the processor's obligations?",
                "mode": NON_DEFAULT_MODE.value,
                "generator": NON_DEFAULT_GENERATOR.value,
            },
            headers=headers,
        )
    ).json()["message_id"]
    ticket = (
        await client.post(
            "/api/v1/auth/stream-tickets", json={"message_id": message_id}, headers=headers
        )
    ).json()["ticket"]
    url = (
        f"/api/v1/conversations/{conversation_id}/messages/{message_id}/stream?ticket={ticket}"
    )
    async with client.stream("GET", url) as response:
        async for _ in response.aiter_lines():
            pass
    return conversation_id


async def test_the_assistant_row_records_the_generator_and_mode_that_answered(
    client, demo_auth, demo_org_id, monkeypatch
) -> None:
    """Sabotage: drop `generator` and `search_mode` from `store_answer`'s INSERT
    and this goes red on both columns at once, reporting `deterministic` and
    `fts` — the values migration 0005's server-side defaults supply, which is
    precisely what makes the bug invisible without this test."""
    conversation_id = await _answer_one_question(client, demo_auth, monkeypatch)

    async with tenant_session(demo_org_id) as session:
        row = (
            await session.execute(
                text(
                    "SELECT generator, search_mode FROM messages "
                    "WHERE conversation_id = :c AND role = 'assistant'"
                ),
                {"c": conversation_id},
            )
        ).mappings().all()

    assert len(row) == 1, "expected exactly one assistant row for one answered question"
    assert row[0]["generator"] == NON_DEFAULT_GENERATOR.value
    assert row[0]["search_mode"] == NON_DEFAULT_MODE.value


async def test_the_user_row_and_the_assistant_row_agree(
    client, demo_auth, demo_org_id, monkeypatch
) -> None:
    """The two rows describe one exchange, and the stream reads its instructions
    off the user row — so a writer that recorded anything else on the assistant
    row would be recording something that did not happen. Asserted as an
    equality rather than against two literals, so the pair cannot drift apart
    while both stay individually plausible.
    """
    conversation_id = await _answer_one_question(client, demo_auth, monkeypatch)

    async with tenant_session(demo_org_id) as session:
        rows = {
            row["role"]: (row["generator"], row["search_mode"])
            for row in (
                await session.execute(
                    text(
                        "SELECT role, generator, search_mode FROM messages "
                        "WHERE conversation_id = :c"
                    ),
                    {"c": conversation_id},
                )
            ).mappings()
        }

    assert rows["assistant"] == rows["user"]


@pytest.mark.parametrize("column", ["generator", "search_mode"])
async def test_the_columns_still_carry_the_defaults_0005_chose(column) -> None:
    """The fix is to stop *relying* on these defaults, not to remove them.

    They are what keeps a row written by anything else non-NULL, which is the
    property migration 0005 argues for. A test that only checked the new writer
    would go green if someone dropped the defaults and left rows nullable.
    """
    async with system_session() as session:
        row = (
            await session.execute(
                text(
                    "SELECT column_default, is_nullable FROM information_schema.columns "
                    "WHERE table_name = 'messages' AND column_name = :c"
                ),
                {"c": column},
            )
        ).mappings().one()
    assert row["column_default"] is not None
    assert row["is_nullable"] == "NO"
