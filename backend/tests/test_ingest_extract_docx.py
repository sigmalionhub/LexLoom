"""What the `.docx` extractor must get right, checked against the publisher.

**Every expected value in this file is quoted from
`app/ingest/sources/nist-sp-800-63b.src.html`** — the preprocessed HTML that
`build_docx_source.sh` committed beside the `.docx` it produced. That file is
here precisely so these tests never take their ground truth from the thing they
are testing. A test that pins whatever the extractor happens to return proves
the extractor is deterministic, which it would be while mangling every word;
`test_ingest_parse.py`'s own chunk-digest test stayed green through exactly that
failure and the repository paid for it once already.

The strings below were not chosen by eye. Each was selected mechanically from
the committed HTML: the table cell and the two paragraphs framing it are the
substantial ones that occur **exactly once** in the document text, so
`list.index()` cannot silently find a different occurrence, and the sentences
are unique ones sampled at three points across the document.
"""

from __future__ import annotations

from collections import Counter

import pytest

from app.ingest.catalogue import CATALOGUE
from app.ingest.extract_docx import Block, extract_docx

SOURCE = CATALOGUE["nist-sp-800-63b"]

# Table 3 of the published document, roughly 55% of the way through. Unique.
TABLE_CELL = "An attacker steals a physical authenticator."
# The last substantial paragraph before that table, and the first after it.
PARAGRAPH_BEFORE_TABLE = (
    "Subscribers sometimes intentionally collude with attackers, and virtually "
    "nothing can be done from an authentication perspective"
)
PARAGRAPH_AFTER_TABLE = (
    "Table 4 summarizes related mechanisms that assist in mitigating the "
    "threats described in Table 3."
)

# Unique sentences at roughly 15%, 45%, 55% and 80% of the document.
VERBATIM_PHRASES = (
    "If used, this key value SHALL be generated by an approved random bit generator",
    "The verification of saved recovery codes SHALL be subject to the throttling requirements",
    "Authenticators used at AAL3 SHALL use approved cryptography.",
    "As a result, users often work around these restrictions counterproductively.",
)

# `<h1>`..`<h4>` counted in the committed HTML.
HEADING_COUNTS = {1: 17, 2: 39, 3: 46, 4: 43}


@pytest.fixture(scope="module")
def blocks() -> list[Block]:
    return extract_docx(SOURCE.path)


def test_the_body_is_walked_in_document_order(blocks: list[Block]) -> None:
    """The defect this exists for, and which no count assertion can see.

    `python-docx` exposes `document.paragraphs`, which yields the body's
    top-level paragraphs and **skips every paragraph inside a table**. The
    obvious implementation — paragraphs, then tables — extracts every word and
    puts all five tables at the end of the document. Every heading count, every
    character total and every phrase assertion still passes; only the order is
    wrong, and the chunker downstream would file half of Sec. 3 under whatever
    heading precedes the tables.

    It is the same class of failure as the PDF path's column-flow bug, which is
    why `parse.py` sets `boxes_flow=None`.
    """
    texts = [block.text for block in blocks]

    def index_of(needle: str) -> int:
        matches = [i for i, text in enumerate(texts) if needle in text]
        assert len(matches) == 1, f"{needle[:40]!r} matched {len(matches)} blocks, expected 1"
        return matches[0]

    assert index_of(PARAGRAPH_BEFORE_TABLE) < index_of(TABLE_CELL) < index_of(PARAGRAPH_AFTER_TABLE)


def test_table_content_is_extracted_at_all(blocks: list[Block]) -> None:
    """The half of the previous test that would still pass if tables vanished
    entirely rather than being reordered."""
    assert any(TABLE_CELL in block.text for block in blocks)


@pytest.mark.parametrize("phrase", VERBATIM_PHRASES)
def test_known_phrases_survive_extraction_intact(blocks: list[Block], phrase: str) -> None:
    """Quoted from the publisher's HTML, never from this extractor's output.

    Deliberately not a single-letter-token ratio: that measurement was tried and
    is worthless here, because ~97% of the single-letter tokens in this document
    are the English article "a". A ratio that cannot move is not a test.
    """
    assert any(phrase in block.text for block in blocks)


def test_every_heading_level_is_read(blocks: list[Block]) -> None:
    """Counts, not a set. `{1, 2, 3, 4}` is satisfied by four headings out of
    145, which is what an extractor that lost a whole level would return."""
    counts = Counter(b.heading_level for b in blocks if b.heading_level is not None)
    assert dict(sorted(counts.items())) == HEADING_COUNTS


def test_nothing_precedes_the_first_heading(blocks: list[Block]) -> None:
    """The invariant the chunker is about to depend on.

    `chunk_docx` gives every chunk the heading in effect at its start, so a
    chunk ahead of the first heading would have no locator to take. This holds
    because `build_docx_source.sh` strips the page's nav, footer, page-switch
    line and build timestamp — and it asserts the same thing at build time.
    Asserted again here, on the committed artefact, because the two can drift:
    a rebuild with a changed strip list would pass the build and break this.
    """
    assert blocks[0].heading_level == 1
    assert blocks[0].text == "ABSTRACT"


def test_styles_are_raw_style_ids(blocks: list[Block]) -> None:
    """`Block.style` carries the raw `w:styleId`, not `paragraph.style.name`.

    The two differ, and the difference has already misled this plan once:
    `styleId` is `TableContents` and `Heading1`, while the display name is
    `Table Contents` and `Heading 1`. Substring-matching "Heading" against the
    display names also sweeps in `ListHeading` and `TableHeading`, which is 187
    phantom headings in this document.
    """
    styles = {block.style for block in blocks}
    assert "Heading1" in styles
    assert "Heading 1" not in styles
    assert all(
        block.heading_level is None
        for block in blocks
        if block.style in {"ListHeading", "TableHeading"}
    )
